// Rebuild the bundled registry/sanctions libs used by the Apify actors from AgentReader src/*.ts.
// Usage: node apify/_build/build.mjs
import { build } from "../../node_modules/esbuild/lib/main.js";
import path from "node:path";
import { fileURLToPath } from "node:url";
const here = path.dirname(fileURLToPath(import.meta.url));
const coreShim = {
  name: "core-shim",
  setup(b) { b.onResolve({ filter: /^\.\/core$/ }, () => ({ path: path.join(here, "core-shim.ts") })); },
};
const common = { bundle: true, platform: "node", format: "esm", target: "node22", external: ["linkedom"], plugins: [coreShim],
  banner: { js: "// GENERATED by apify/_build/build.mjs from AgentReader src/*.ts — do not edit by hand." }, absWorkingDir: here };
await build({ ...common, entryPoints: ["eu-registries.ts"], outfile: "../eu-company-registry-check/src/registries.js" });
await build({ ...common, entryPoints: ["sanctions.ts"], outfile: "../sanctions-screening-batch/src/sanctions-lib.js" });
console.log("built");
