import { Actor } from "apify";
import { wrapFetchWithPayment, x402Client } from "@x402/fetch";
import { ExactEvmScheme } from "@x402/evm/exact/client";
import { privateKeyToAccount } from "viem/accounts";

await Actor.init();
const input = (await Actor.getInput()) || {};
const { domain, number, name, vat, agentreaderPrivateKey } = input;
if (!agentreaderPrivateKey) throw new Error("agentreaderPrivateKey required");
if (!domain && !number && !name && !vat) throw new Error("Provide domain and/or UK number/name and/or vat");
const account = privateKeyToAccount(agentreaderPrivateKey.startsWith("0x") ? agentreaderPrivateKey : `0x${agentreaderPrivateKey}`);
const client = new x402Client().register("eip155:8453", new ExactEvmScheme(account));
const pay = wrapFetchWithPayment(fetch, client);
const q = new URLSearchParams();
if (domain) q.set("domain", domain);
if (number) q.set("number", number);
if (name) q.set("name", name);
if (vat) q.set("vat", vat);
const res = await pay(`https://api.axiomworks.co.uk/kyb?${q}`);
if (!res.ok) throw new Error(`AgentReader ${res.status}: ${(await res.text()).slice(0, 300)}`);
const data = await res.json();
await Actor.pushData(data);
await Actor.exit();
